const assert=require('node:assert/strict');
const fs=require('node:fs'),vm=require('node:vm'),path=require('node:path');
const base=path.join(__dirname,'..');
const ctx=vm.createContext({window:{},console});
vm.runInContext(fs.readFileSync(path.join(base,'js/custom-food-editor.js'),'utf8'),ctx);
const edit=ctx.window.FitCustomFoodEditor.update;
let count=0;
const original={id:'personal-1',name:'ลูกชิ้นนึ่ง',unit:'1 เสิร์ฟ',kcal:170,protein:11,carbs:18,fat:6,baseGrams:null,macroKnown:true,macroEstimated:true,group:'เมนูของฉัน'};
const list=[original,{id:'personal-2',name:'ไอศกรีม',unit:'1 เสิร์ฟ',kcal:150}];
const history=[{id:'log-1',foodId:'personal-1',name:original.name,kcal:170,protein:11,carbs:18,fat:6,servings:2}];
const templates=[{id:'template-1',items:[{name:original.name,kcal:170,servings:1}]}];
const updateFields={name:'ลูกชิ้นนึ่ง (สูตรใหม่)',unit:'5 ลูก',baseGrams:'120',kcal:'195',protein:'15',carbs:'19',fat:'7',macroStatus:'known'};
const revised=edit(original,updateFields,list);assert.equal(revised.id,original.id);count++;
assert.equal(revised.name,updateFields.name);count++;
assert.equal(revised.unit,updateFields.unit);count++;
assert.equal(revised.baseGrams,120);count++;
assert.equal(revised.kcal,195);count++;
assert.equal(revised.protein,15);count++;
assert.equal(revised.carbs,19);count++;
assert.equal(revised.fat,7);count++;
assert.equal(revised.macroKnown,true);count++;
assert.equal(revised.macroEstimated,false);count++;
assert.equal(original.kcal,170);count++;
assert.equal(history[0].kcal,170);count++;
assert.equal(templates[0].items[0].kcal,170);count++;
const later={...revised,servings:2};assert.equal(later.kcal*later.servings,390);count++;
const kcalOnly=edit(original,{...updateFields,macroStatus:'unknown',protein:'',carbs:'',fat:''},list);
assert.equal(kcalOnly.macroKnown,false);count++;
assert.equal(kcalOnly.protein,0);count++;
assert.equal(kcalOnly.carbs,0);count++;
assert.equal(kcalOnly.fat,0);count++;
assert.throws(()=>edit(original,{...updateFields,name:'ไอศกรีม'},list));count++;
assert.throws(()=>edit(original,{...updateFields,kcal:''},list));count++;
assert.throws(()=>edit(original,{...updateFields,kcal:'-1'},list));count++;
assert.throws(()=>edit(original,{...updateFields,baseGrams:'0'},list));count++;
assert.throws(()=>edit(original,{...updateFields,protein:''},list));count++;
assert.throws(()=>edit(original,{...updateFields,name:' '},list));count++;
const app=fs.readFileSync(path.join(base,'js/app.js'),'utf8');
assert(app.includes('data-action="food-library-edit"'));count++;
assert(app.includes("if(a==='food-library-edit')"));count++;
assert(app.includes("if(form.id==='custom-food-form')"));count++;
assert(app.includes("state.customFoods=state.customFoods.map(x=>x.id===existing.id?updated:x)"));count++;
assert(app.includes('data-action="food-library-delete"'));count++;
const html=fs.readFileSync(path.join(base,'index.html'),'utf8');assert(html.includes('js/custom-food-editor.js?v=1.9.4'));count++;
console.log('V1.9.4 custom food editor tests passed:',count);
