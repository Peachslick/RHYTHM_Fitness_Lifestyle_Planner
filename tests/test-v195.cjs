const assert=require('node:assert/strict');
const fs=require('node:fs'),vm=require('node:vm'),path=require('node:path');
const root=path.resolve(__dirname,'..');const ctx=vm.createContext({window:{},console});
vm.runInContext(fs.readFileSync(path.join(root,'js/daily-experience.js'),'utf8'),ctx);
const Daily=ctx.window.FitDaily;let count=0;
const eq=(a,b,msg)=>{assert.equal(a,b,msg);count++};
const ok=(a,msg)=>{assert.ok(a,msg);count++};
const today='2026-10-21',old='2026-10-20';
const state={meals:[{id:'a',date:old,meal:'breakfast',name:'ข้าวต้ม',unit:'ถ้วย',servings:1,kcal:180},{id:'b',date:old,meal:'breakfast',name:'ไข่ต้ม',unit:'ฟอง',servings:2,kcal:70},{id:'c',date:'2026-10-19',meal:'breakfast',name:'ไข่ต้ม',unit:'ฟอง',servings:1,kcal:70},{id:'d',date:today,meal:'lunch',name:'ไก่ย่าง',unit:'จาน',servings:1,kcal:290}],
 sessions:[{date:old,exercises:[{name:'Dumbbell Row',setLog:[{reps:8,load:10,warmup:true},{reps:12,load:15,warmup:false}]}]}],
 sleeps:[{date:old,bed:'22:00',wake:'06:00'}],weights:[{date:old,weight:68.5}],checkins:[]};
const summary=Daily.todaySummary(state,today,{type:'pull'});
eq(summary.meals.length,1,'today one meal');eq(summary.sleep,null,'missing sleep is null');eq(summary.isRest,false,'active day');eq(summary.indicators[1].done,true,'meal completed');eq(summary.indicators[4].done,false,'weight optional missing');
eq(Daily.todaySummary(state,today,{type:'rest'}).indicators[2].done,true,'rest day automatically no log needed');
eq(Daily.lastSameMeal(state,today,'breakfast').length,2,'last same meal entire group');
eq(Daily.lastSameMeal(state,today,'dinner').length,0,'no prior dinner');
eq(Daily.topRepeated(state,today,3)[0].row.name,'ไข่ต้ม','common repeated meal');
eq(Daily.latest(state.weights,today,true).weight,68.5,'previous weight');
eq(Daily.latest(state.sleeps,today,true).bed,'22:00','prior sleep');
const prior=Daily.previousExercise(state,today,{name:'DUMBBELL ROW'});
eq(prior.date,old,'prior session date');eq(prior.set.reps,12,'prefers last working set');eq(prior.set.load,15,'prior external weight');
eq(Daily.previousExercise(state,today,{name:'Plank'}),null,'no invented reference');
let i=0;const copied=Daily.safeCopyRows(Daily.lastSameMeal(state,today,'breakfast'),today,()=>`new${++i}`);
eq(copied.length,2,'two copied');eq(copied[0].date,today,'new date');eq(copied[0].copiedFrom,'a','traceability');eq(state.meals[0].id,'a','source immutable');eq(state.meals.length,4,'state not mutated');
const app=fs.readFileSync(path.join(root,'js/app.js'),'utf8'),html=fs.readFileSync(path.join(root,'index.html'),'utf8'),css=fs.readFileSync(path.join(root,'css/styles.css'),'utf8');
ok(html.includes('js/daily-experience.js?v=1.9.5'),'script loaded');
ok(app.includes('function dailyExperiencePanel('),'daily UI');
ok(app.includes('function openDailyMealPicker('),'daily food picker');
ok(app.includes('function openDailyCopyPicker('),'copy picker');
ok(app.includes("if(a==='daily-template')"),'one-click template');
ok(app.includes("if(a==='daily-repeat')"),'one-click repeat');
ok(app.includes("if(a==='daily-copy-type')"),'copy past whole meal');
ok(app.includes('Daily.previousExercise(state,d.date,ex)'),'live last performed');
ok(app.includes('history?.set?.load??ex.load'),'live weight prefill editable');
ok(app.includes('last?.bed'), 'sleep times only as defaults');
ok(app.includes('last?.distanceKm'), 'run distance default');
ok(app.includes('last?.weight'), 'weight default');
ok(app.includes('Daily.safeCopyRows'), 'copied source immutable');
ok(css.includes('.daily-action-grid'),'responsive CSS');
console.log(`PASS: ${count} V1.9.5 daily dashboard, autofill safety, non-mutation, and integration assertions`);
